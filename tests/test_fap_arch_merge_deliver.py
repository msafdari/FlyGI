def test_l2_first_step_is_a_clean_pair_merge() -> None:
    # Merge capture is Euclidean 8.00 in / 8.06 out (measured), so the one
    # emitted step must capture EXACTLY two same-stage creatures: two
    # centres within 7.75 of the click and every other centre 8.6+ away.
    archetype = MergeDeliverArchetype()
    grid = board(L2_ENTRY)
    parse = archetype.match(grid)
    steps = archetype.next_actions(parse, grid)
    assert len(steps) == 1  # autonomous world: one step per call
    step = steps[0]
    assert step.action == 6
    dists = sorted(
        hypot(c.centre[0] - step.y, c.centre[1] - step.x)
        for c in parse.creatures
    )
    assert dists[1] <= 7.75 and dists[2] >= 8.6



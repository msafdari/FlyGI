def test_merge_click_keeps_third_wheels_beyond_capture() -> None:
    # Measured: 8.00 captures, 8.06 does not; an unintended third wheel
    # inside the radius would fuse three-ways and destroy mass.
    creatures = [
        creature(1, 1, 30, 28),
        creature(1, 1, 30, 36),
        creature(1, 1, 34, 32),  # sits right at the pair's midpoint
    ]
    p = parse_of((2,), creatures, [disc(11, 2)])
    click = _merge_click(p, 0, 1, set())
    assert click is not None
    d0 = hypot(30 - click[0], 28 - click[1])
    d1 = hypot(30 - click[0], 36 - click[1])
    d2 = hypot(34 - click[0], 32 - click[1])
    assert d0 <= 7.75 and d1 <= 7.75 and d2 >= 8.6



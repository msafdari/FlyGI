def test_dock_click_lands_overlapping_the_disc() -> None:
    d0 = disc(23, 29)
    piece = creature(4, 4, 34, 30)  # centre (35.5, 31.5), cap 8.8
    p = parse_of((4,), [piece], [d0])
    click = _dock_click(p, 0, d0, set())
    assert click is not None
    r0, c0 = _landing_anchor(4, click)
    footprint = {(r0 + i, c0 + j) for i in range(4) for j in range(4)}
    assert footprint & d0.cells
    assert hypot(piece.centre[0] - click[0], piece.centre[1] - click[1]) <= 8.8



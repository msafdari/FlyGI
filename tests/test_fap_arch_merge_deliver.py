def board(text: str) -> np.ndarray:
    rows = [line for line in text.strip().splitlines()]
    assert len(rows) == 64 and all(len(r) == 64 for r in rows)
    return np.array(
        [[int(ch, 16) for ch in line] for line in rows], dtype=np.int16
    )


def creature(stage: int, size: int, r0: int, c0: int) -> _Creature:
    return _Creature(
        stage=stage,
        size=size,
        centre=(r0 + (size - 1) / 2.0, c0 + (size - 1) / 2.0),
        anchor=(r0, c0),
    )


def disc(ar: int, ac: int) -> _Disc:
    return _Disc(
        anchor=(ar, ac),
        centre=(ar + 4.0, ac + 4.0),
        cells=frozenset((ar + dr, ac + dc) for dr, dc in _DISC_CELLS),
    )


def parse_of(
    goals: tuple[int, ...],
    creatures: list[_Creature],
    discs: list[_Disc],
    predators: list[tuple[float, float]] | None = None,
) -> MergeBoardParse:
    return MergeBoardParse(
        goals=goals,
        creatures=creatures,
        discs=discs,
        predators=predators or [],
        timer=64,
    )



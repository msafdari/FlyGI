def test_allocation_direct_then_build_then_fail() -> None:
    d0 = disc(11, 28)
    # direct: a stage-4 exists for a stage-4 goal
    p = parse_of((4,), [creature(4, 4, 30, 30)], [d0])
    assert _allocate(p) == [("direct", (0,))]
    # build: 2+2+1+1+2 units cover mass 8 largest-first (indices 0,1,4,2,3)
    p = parse_of(
        (4,),
        [
            creature(2, 2, 20, 20),
            creature(2, 2, 20, 30),
            creature(1, 1, 40, 20),
            creature(1, 1, 40, 24),
            creature(2, 2, 44, 21),
        ],
        [d0],
    )
    (kind, members) = _allocate(p)[0]
    assert kind == "build"
    assert sorted(members) == [0, 1, 2, 3, 4]
    # fail: not enough mass and nothing bigger to chew
    p = parse_of((4,), [creature(1, 1, 40, 20)], [d0])
    assert _allocate(p) == [("fail", ())]


def test_allocation_sacrifices_only_when_mass_allows() -> None:
    # Two predators, six 2x2s, goal 4x4 (mass 8 of 12): the first pass
    # excludes each predator's nearest creature (the measured L5 bait
    # pattern), so the build must avoid indices 0 and 1.
    creatures = [
        creature(2, 2, 30, 4),   # nearest to predator W: doomed
        creature(2, 2, 30, 44),  # nearest to predator E: doomed
        creature(2, 2, 14, 14),
        creature(2, 2, 14, 24),
        creature(2, 2, 50, 14),
        creature(2, 2, 50, 24),
    ]
    p = parse_of((4,), creatures, [disc(11, 28)], [(38.0, 5.0), (38.0, 45.0)])
    doomed = frozenset({0, 1})
    (kind, members) = _allocate(p, doomed)[0]
    assert kind == "build"
    assert set(members).isdisjoint(doomed)



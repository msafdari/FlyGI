def test_abstains_on_random_grids() -> None:
    rng = np.random.default_rng(20260928)
    archetype = PipDoorArchetype()
    for _ in range(50):
        grid = rng.integers(0, 16, size=(64, 64), dtype=np.int16)
        assert archetype.match(grid) is None



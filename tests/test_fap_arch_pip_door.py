def board(text: str) -> np.ndarray:
    rows = text.strip().splitlines()
    assert len(rows) == 64 and all(len(r) == 64 for r in rows)
    return np.array(
        [[int(ch, 16) for ch in row] for row in rows], dtype=np.int16
    )


def program(name: str) -> list[Step]:
    steps = json.loads((DOSSIER / name).read_text())
    return [
        Step(action=int(s["action"]), x=s.get("x"), y=s.get("y")) for s in steps
    ]


def plan(grid: np.ndarray) -> list[Step]:
    archetype = PipDoorArchetype()
    parse = archetype.match(grid)
    assert parse is not None
    return archetype.next_actions(parse, grid)


# ------------------------------------------------------------------ positives


def test_l3_entry_plan_equals_verified_program_punch_phase() -> None:
    # Verified L3 program: click(30,50) click(30,55) RIGHT click(30,60),
    # then rolls to the dock (the door is gone by then, match() abstains,
    # and the seated PipPunchRollArchetype rolls home -- measured).
    assert plan(board(L3_ENTRY)) == program("L3_program.json")[:4]


def test_l4_entry_plan_is_the_shrink_punch() -> None:
    # Verified L4 program opens with the f-diamond: the die is 4x4 and a
    # shrink display exists, so the planner punches it first, no arming.
    assert plan(board(L4_ENTRY)) == program("L4_program.json")[:4]


def test_l4_post_shrink_plan_equals_verified_arming_program() -> None:
    # DOWN x5 to the key corridor, T, C, LEFT arming, completing B.
    assert plan(board(L4_SHRUNK)) == program("L4_program.json")[4:13]


def test_arming_roll_sits_between_penultimate_and_final_click() -> None:
    steps = plan(board(L3_ENTRY))
    assert steps[-2].action in (1, 2, 3, 4)  # the arming roll
    assert steps[-1].action == 6  # the completing click
    assert all(s.action == 6 for s in steps[:-2])


def test_all_steps_legal() -> None:
    for text in (L3_ENTRY, L4_ENTRY, L4_SHRUNK):
        for s in plan(board(text)):
            assert s.action in (1, 2, 3, 4, 6)
            if s.action == 6:
                assert 0 <= s.x < 64 and 0 <= s.y < 64


# ------------------------------------------------------------ planner details


def test_stray_punch_is_cleared_first() -> None:
    grid = board(L3_ENTRY)
    # Punch a non-pattern pip cell (top-left cell, rows 49-51 / cols 24-26).
    grid[49:52, 24:27] = 14
    steps = plan(grid)
    assert steps == [Step(action=6, x=25, y=50)]


def test_partially_punched_pattern_completes_with_arming() -> None:
    grid = board(L3_ENTRY)
    grid[49:52, 29:32] = 14  # top pattern cell already punched
    steps = plan(grid)
    assert steps == [
        Step(action=6, x=30, y=55),
        Step(action=4),
        Step(action=6, x=30, y=60),
    ]


def test_no_line_of_sight_abstains_from_planning() -> None:
    grid = board(L3_ENTRY)
    # Wall the gate corridor (rows 23-24, cols 51-54): no ray reaches the
    # key box from anywhere the die can stand, so the planner returns no
    # steps and the executor falls through to the next archetype.
    grid[23:25, 51:55] = 5
    archetype = PipDoorArchetype()
    parse = archetype.match(grid)
    assert parse is not None
    assert archetype.next_actions(parse, grid) == []


def test_reset_is_safe_and_stateless() -> None:
    archetype = PipDoorArchetype()
    assert archetype.name == "pip_door"
    before = archetype.match(board(L3_ENTRY))
    archetype.reset()
    after = archetype.match(board(L3_ENTRY))
    assert before is not None and after is not None
    assert archetype.next_actions(after, board(L3_ENTRY)) == plan(board(L3_ENTRY))



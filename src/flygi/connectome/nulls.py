"""Seeded directed degree-preserving null graphs and their invariant checks.

The preregistered primary control is a directed degree-preserving rewiring: a
graph with every node's in-degree and out-degree held exactly equal to the real
graph's, and with all higher-order structure randomized. It is generated by
repeated directed double-edge swaps.

Given two directed edges ``a -> b`` and ``c -> d``, a swap replaces them with
``a -> d`` and ``c -> b``. That leaves ``out_degree(a)``, ``out_degree(c)``,
``in_degree(b)`` and ``in_degree(d)`` unchanged. A swap is rejected when it
would create a self-edge (unless self-edges are permitted), duplicate an
aggregated edge that already exists, or act on a degenerate pair.

Weight rule, declared once here and recorded in every null manifest: each edge
weight travels with its presynaptic slot. When ``a -> b`` becomes ``a -> d`` it
keeps its weight. The global weight multiset and every node's outgoing weight
multiset are therefore preserved exactly by the rewiring itself.

Normalization: this module rewires whatever matrix it is given. The caller is
responsible for applying the same declared normalization to the null that the
real condition uses. When the input is an already-normalized runtime matrix,
re-applying incoming-L1 normalization afterwards is required, because moving
edges between postsynaptic rows changes those rows' sums.
"""

from __future__ import annotations

from dataclasses import dataclass
from typing import Any, Literal

import numpy as np
from numpy.typing import NDArray
from scipy import sparse

NullKind = Literal["degree_preserving", "weight_shuffle", "sign_shuffle"]


class NullValidationError(ValueError):
    """Raised when a null graph violates a declared invariant."""


@dataclass(frozen=True)
class NullOptions:
    """Declared, recorded choices that change a generated null graph."""

    kind: NullKind = "degree_preserving"
    swaps_per_edge: float = 10.0
    allow_self_edges: bool = False
    batch_pairs: int = 2_000_000
    max_batches: int = 10_000

    def __post_init__(self) -> None:
        if self.kind not in ("degree_preserving", "weight_shuffle", "sign_shuffle"):
            raise ValueError(f"Unknown null kind: {self.kind!r}")
        if not np.isfinite(self.swaps_per_edge) or self.swaps_per_edge <= 0:
            raise ValueError("swaps_per_edge must be finite and positive")
        if self.batch_pairs <= 0:
            raise ValueError("batch_pairs must be positive")
        if self.max_batches <= 0:
            raise ValueError("max_batches must be positive")


def _as_canonical_csr(matrix: sparse.spmatrix) -> sparse.csr_matrix:
    if not sparse.issparse(matrix):
        raise TypeError("null generation requires a scipy sparse matrix")
    csr = matrix.tocsr(copy=True)
    if csr.ndim != 2 or csr.shape[0] != csr.shape[1]:
        raise NullValidationError("null generation requires a square matrix")
    csr.sort_indices()
    csr.sum_duplicates()
    return csr


def _coo_arrays(
    matrix: sparse.csr_matrix,
) -> tuple[NDArray[np.int64], NDArray[np.int64], NDArray[np.float32]]:
    """Return ``(pre, post, weight)`` for the ``W[post, pre]`` convention."""

    coo = matrix.tocoo(copy=False)
    post = coo.row.astype(np.int64, copy=False)
    pre = coo.col.astype(np.int64, copy=False)
    return pre.copy(), post.copy(), coo.data.astype(np.float32, copy=True)


def _contains(sorted_keys: NDArray[np.int64], query: NDArray[np.int64]) -> NDArray[np.bool_]:
    """Vectorized membership test against a sorted, unique key array."""

    if query.size == 0:
        return np.zeros(0, dtype=bool)
    position = np.searchsorted(sorted_keys, query)
    np.clip(position, 0, max(len(sorted_keys) - 1, 0), out=position)
    if len(sorted_keys) == 0:
        return np.zeros(len(query), dtype=bool)
    return sorted_keys[position] == query


def _remove_and_insert(
    sorted_keys: NDArray[np.int64],
    removed: NDArray[np.int64],
    inserted: NDArray[np.int64],
) -> NDArray[np.int64]:
    """Update a sorted key array in O(n) without a full re-sort."""

    positions = np.searchsorted(sorted_keys, removed)
    keep = np.ones(len(sorted_keys), dtype=bool)
    keep[positions] = False
    remaining = sorted_keys[keep]
    if inserted.size == 0:
        return remaining
    new_sorted = np.sort(inserted)
    return np.insert(remaining, np.searchsorted(remaining, new_sorted), new_sorted)


def degree_preserving_rewire(
    matrix: sparse.spmatrix,
    *,
    seed: int,
    options: NullOptions | None = None,
) -> tuple[sparse.csr_matrix, dict[str, Any]]:
    """Rewire a directed graph, preserving every in-degree and out-degree.

    Returns the rewired matrix and a statistics record. The matrix is **not**
    renormalized; the caller applies the real condition's normalization.
    """

    settings = options or NullOptions()
    if settings.kind != "degree_preserving":
        raise ValueError(f"degree_preserving_rewire cannot generate kind {settings.kind!r}")

    csr = _as_canonical_csr(matrix)
    node_count = int(csr.shape[0])
    pre, post, weights = _coo_arrays(csr)
    edge_count = len(pre)
    if edge_count < 2:
        raise NullValidationError("degree-preserving rewiring needs at least two edges")

    keys = pre * node_count + post
    sorted_keys = np.sort(keys)
    if len(np.unique(sorted_keys)) != edge_count:
        raise NullValidationError("input graph contains duplicate aggregated edges")

    generator = np.random.default_rng(seed)
    target_swaps = round(settings.swaps_per_edge * edge_count)
    pair_budget = min(settings.batch_pairs, edge_count // 2)
    if pair_budget < 1:
        raise NullValidationError("graph is too small for batched double-edge swaps")

    accepted = 0
    proposed = 0
    batches = 0
    rejected = {
        "degenerate": 0,
        "self_edge": 0,
        "existing_edge": 0,
        "batch_collision": 0,
    }

    while accepted < target_swaps and batches < settings.max_batches:
        batches += 1
        take = min(2 * pair_budget, 2 * (edge_count // 2))
        sample = generator.permutation(edge_count)[:take]
        left = sample[0::2]
        right = sample[1::2]
        proposed += len(left)

        a, b = pre[left], post[left]
        c, d = pre[right], post[right]

        viable = (a != c) & (b != d)
        rejected["degenerate"] += int(np.count_nonzero(~viable))
        if not settings.allow_self_edges:
            no_loop = (a != d) & (c != b)
            rejected["self_edge"] += int(np.count_nonzero(viable & ~no_loop))
            viable &= no_loop

        left, right = left[viable], right[viable]
        a, b, c, d = a[viable], b[viable], c[viable], d[viable]

        first = a * node_count + d
        second = c * node_count + b
        free = ~(_contains(sorted_keys, first) | _contains(sorted_keys, second))
        rejected["existing_edge"] += int(np.count_nonzero(~free))
        left, right = left[free], right[free]
        a, b, c, d = a[free], b[free], c[free], d[free]
        first, second = first[free], second[free]

        # Two accepted swaps in one batch must not both create the same edge.
        candidates = np.concatenate([first, second])
        unique_keys, counts = np.unique(candidates, return_counts=True)
        repeated = unique_keys[counts > 1]
        clean = ~(_contains(repeated, first) | _contains(repeated, second))
        rejected["batch_collision"] += int(np.count_nonzero(~clean))
        left, right = left[clean], right[clean]
        b, d = b[clean], d[clean]
        first, second = first[clean], second[clean]
        if left.size == 0:
            continue

        removed = np.concatenate([pre[left] * node_count + b, pre[right] * node_count + d])
        post[left] = d
        post[right] = b
        sorted_keys = _remove_and_insert(sorted_keys, removed, np.concatenate([first, second]))
        accepted += int(left.size)

    rewired = sparse.csr_matrix(
        (weights, (post, pre)), shape=(node_count, node_count), dtype=np.float32
    )
    rewired.sort_indices()
    rewired.sum_duplicates()
    if rewired.nnz != edge_count:
        raise NullValidationError(
            f"rewiring changed the edge count: expected {edge_count}, observed {rewired.nnz}"
        )

    statistics = {
        "kind": "degree_preserving",
        "seed": int(seed),
        "nodes": node_count,
        "edges": edge_count,
        "target_swaps": target_swaps,
        "accepted_swaps": accepted,
        "proposed_swaps": proposed,
        "batches": batches,
        "swaps_per_edge_requested": float(settings.swaps_per_edge),
        "swaps_per_edge_achieved": accepted / edge_count,
        "acceptance_rate": (accepted / proposed) if proposed else 0.0,
        "rejected": dict(rejected),
        "allow_self_edges": bool(settings.allow_self_edges),
        "reached_target": accepted >= target_swaps,
        "weight_rule": "edge weight travels with its presynaptic slot",
        "normalization_applied": False,
    }
    if not statistics["reached_target"]:
        raise NullValidationError(
            f"rewiring stopped after {batches} batches with {accepted} of "
            f"{target_swaps} swaps; raise max_batches or lower swaps_per_edge"
        )
    return rewired, statistics


def weight_shuffle(
    matrix: sparse.spmatrix,
    *,
    seed: int,
    within_presynaptic: bool = True,
) -> tuple[sparse.csr_matrix, dict[str, Any]]:
    """Permute |weight| magnitudes over the EXISTING edges; topology and
    per-edge signs held fixed (H-STAGEA-NULL-DECOMPOSITION, frozen
    2026-10-23 in docs/arenas/task10_menu/killtest_design.md section 7).

    within_presynaptic=True (the PRIMARY variant, AC-N1): magnitudes are
    permuted within each presynaptic neuron's outgoing edge set -- the
    clean complement of the degree-preserving rewire, whose declared
    weight rule preserves exactly those per-presynaptic multisets.
    within_presynaptic=False: one global permutation over all edges.

    The sign of every edge stays in place (per-edge signs identical to
    the real graph -- a declared invariant); only |w| moves.
    """

    csr = _as_canonical_csr(matrix)
    node_count = int(csr.shape[0])
    pre, post, weights = _coo_arrays(csr)
    edge_count = len(pre)
    if edge_count < 2:
        raise NullValidationError("weight shuffle needs at least two edges")

    signs = np.sign(weights).astype(np.float32)
    magnitudes = np.abs(weights).astype(np.float32)
    generator = np.random.default_rng(seed)

    shuffled = magnitudes.copy()
    if within_presynaptic:
        order = np.argsort(pre, kind="stable")
        sorted_pre = pre[order]
        boundaries = np.flatnonzero(np.diff(sorted_pre)) + 1
        for group in np.split(order, boundaries):
            if group.size > 1:
                shuffled[group] = magnitudes[group[generator.permutation(group.size)]]
    else:
        shuffled = magnitudes[generator.permutation(edge_count)]

    new_weights = (signs * shuffled).astype(np.float32)
    result = sparse.csr_matrix(
        (new_weights, (post, pre)), shape=(node_count, node_count), dtype=np.float32
    )
    result.sort_indices()

    changed = float(np.mean(~np.isclose(shuffled, magnitudes)))
    statistics = {
        "kind": "weight_shuffle",
        "variant": "within_presynaptic" if within_presynaptic else "global",
        "seed": int(seed),
        "nodes": node_count,
        "edges": edge_count,
        # Degeneracy floor (frozen >= 0.5): below it the permutation is
        # near-identity and the caller must BLOCK, never read a p.
        "fraction_magnitudes_changed": changed,
        "normalization_applied": False,
    }
    return result, statistics


def sign_shuffle(
    matrix: sparse.spmatrix,
    *,
    seed: int,
) -> tuple[sparse.csr_matrix, dict[str, Any]]:
    """Permute the per-presynaptic-neuron sign assignment; topology and
    per-edge |weight| held fixed (H-STAGEA-NULL-DECOMPOSITION, AC-N2:
    signs are per-neuron transmitter properties, so the shuffle moves
    whole columns' signs -- Dale-consistent by construction; a per-edge
    sign permutation was rejected as non-biological).

    Requires the input to satisfy column sign-constancy (every
    presynaptic neuron's outgoing edges share one sign); a mixed-sign
    column raises NullValidationError -- the caller's BLOCKED floor,
    never a verdict.
    """

    csr = _as_canonical_csr(matrix)
    node_count = int(csr.shape[0])
    pre, post, weights = _coo_arrays(csr)
    if len(pre) < 1:
        raise NullValidationError("sign shuffle needs at least one edge")

    signs = np.sign(weights)
    bearing = np.unique(pre)
    column_sign = np.zeros(node_count, dtype=np.float32)
    for column in bearing:
        edge_signs = np.unique(signs[pre == column])
        edge_signs = edge_signs[edge_signs != 0]
        if edge_signs.size > 1:
            raise NullValidationError(
                f"presynaptic column {int(column)} carries mixed signs; "
                "sign shuffle requires column sign-constancy"
            )
        column_sign[column] = edge_signs[0] if edge_signs.size else 1.0

    generator = np.random.default_rng(seed)
    permuted = column_sign.copy()
    permuted[bearing] = column_sign[bearing][generator.permutation(bearing.size)]

    new_weights = (np.abs(weights) * permuted[pre]).astype(np.float32)
    result = sparse.csr_matrix(
        (new_weights, (post, pre)), shape=(node_count, node_count), dtype=np.float32
    )
    result.sort_indices()

    multiset = column_sign[bearing]
    constant = bool(np.all(multiset == multiset[0])) if bearing.size else True
    statistics = {
        "kind": "sign_shuffle",
        "seed": int(seed),
        "nodes": node_count,
        "edges": int(len(pre)),
        "sign_bearing_columns": int(bearing.size),
        # Degeneracy flag (frozen): a constant sign multiset makes the
        # shuffle the identity -- the caller reports NA, never a p.
        "constant_sign_multiset": constant,
        "fraction_signs_changed": float(np.mean(permuted[pre] != signs))
        if len(pre)
        else 0.0,
        "normalization_applied": False,
    }
    return result, statistics


def shuffle_invariants(
    original: sparse.spmatrix,
    shuffled: sparse.spmatrix,
    *,
    family: Literal["weight", "sign"],
    within_presynaptic: bool = True,
) -> dict[str, Any]:
    """Verify the declared invariants of the second null family
    (killtest_design.md section 7): the edge set is IDENTICAL to the
    real graph (unlike the rewire), and per family the untouched
    component is bit-preserved."""

    source = _as_canonical_csr(original)
    target = _as_canonical_csr(shuffled)
    if source.shape != target.shape:
        raise NullValidationError("shuffled graph must match the real graph's shape")

    s_pre, s_post, s_w = _coo_arrays(source)
    t_pre, t_post, t_w = _coo_arrays(target)
    node_count = int(source.shape[0])
    same_edges = bool(
        np.array_equal(s_pre * node_count + s_post, t_pre * node_count + t_post)
    )

    record: dict[str, Any] = {
        "family": family,
        "edges": int(len(s_pre)),
        "edge_set_identical": same_edges,
    }
    failures: list[str] = []
    if not same_edges:
        failures.append("edge set changed")

    if family == "weight":
        record["sign_pattern_identical"] = bool(
            np.array_equal(np.sign(s_w), np.sign(t_w))
        )
        if not record["sign_pattern_identical"]:
            failures.append("per-edge signs changed")
        if within_presynaptic:
            ok = True
            for column in np.unique(s_pre):
                mask = s_pre == column
                if not np.array_equal(
                    np.sort(np.abs(s_w[mask])), np.sort(np.abs(t_w[mask]))
                ):
                    ok = False
                    break
            record["per_presynaptic_magnitude_multisets_identical"] = ok
            if not ok:
                failures.append("per-presynaptic |w| multiset changed")
        else:
            record["magnitude_multiset_identical"] = bool(
                np.array_equal(np.sort(np.abs(s_w)), np.sort(np.abs(t_w)))
            )
            if not record["magnitude_multiset_identical"]:
                failures.append("global |w| multiset changed")
    else:
        record["magnitudes_identical_per_edge"] = bool(
            np.allclose(np.abs(s_w), np.abs(t_w))
        )
        if not record["magnitudes_identical_per_edge"]:
            failures.append("per-edge |w| changed")

        def _column_signs(pre: NDArray[np.int64], w: NDArray[np.float32]):
            out = {}
            for column in np.unique(pre):
                edge_signs = np.unique(np.sign(w[pre == column]))
                edge_signs = edge_signs[edge_signs != 0]
                if edge_signs.size > 1:
                    return None
                out[int(column)] = float(edge_signs[0]) if edge_signs.size else 1.0
            return out

        s_cols = _column_signs(s_pre, s_w)
        t_cols = _column_signs(t_pre, t_w)
        record["column_sign_constancy_preserved"] = t_cols is not None
        if t_cols is None:
            failures.append("column sign-constancy violated")
        elif s_cols is not None:
            record["column_sign_multiset_identical"] = sorted(
                s_cols.values()
            ) == sorted(t_cols.values())
            if not record["column_sign_multiset_identical"]:
                failures.append("column-sign multiset changed")

    record["failures"] = failures
    record["valid"] = not failures
    return record


def directed_degrees(
    matrix: sparse.spmatrix,
) -> tuple[NDArray[np.int64], NDArray[np.int64]]:
    """Return ``(in_degree, out_degree)`` under the ``W[post, pre]`` convention."""

    csr = matrix.tocsr(copy=False)
    node_count = int(csr.shape[0])
    in_degree = np.diff(csr.indptr).astype(np.int64, copy=False)
    out_degree = np.bincount(csr.indices, minlength=node_count).astype(np.int64, copy=False)
    return in_degree, out_degree


def null_invariants(
    original: sparse.spmatrix,
    rewired: sparse.spmatrix,
    *,
    expect_identical_weight_multiset: bool = True,
    preserved_groups: dict[str, NDArray[np.integer]] | None = None,
) -> dict[str, Any]:
    """Verify every declared invariant of a generated null graph."""

    source = original.tocsr(copy=False)
    target = rewired.tocsr(copy=False)
    if source.shape != target.shape:
        raise NullValidationError("null graph must have the same shape as the real graph")

    source_in, source_out = directed_degrees(source)
    target_in, target_out = directed_degrees(target)
    in_matches = bool(np.array_equal(source_in, target_in))
    out_matches = bool(np.array_equal(source_out, target_out))

    weight_matches = None
    if expect_identical_weight_multiset:
        weight_matches = bool(np.array_equal(np.sort(source.data), np.sort(target.data)))

    diagonal = np.asarray(target.diagonal())
    self_edges = int(np.count_nonzero(diagonal))

    node_count = int(target.shape[0])
    target_coo = target.tocoo(copy=False)
    target_keys = target_coo.col.astype(np.int64) * node_count + target_coo.row.astype(np.int64)
    duplicates = int(len(target_keys) - len(np.unique(target_keys)))

    source_coo = source.tocoo(copy=False)
    source_keys = source_coo.col.astype(np.int64) * node_count + source_coo.row.astype(np.int64)
    shared = int(np.intersect1d(np.sort(source_keys), np.sort(target_keys)).size)

    record: dict[str, Any] = {
        "edges": int(target.nnz),
        "edge_count_matches": int(source.nnz) == int(target.nnz),
        "in_degree_matches": in_matches,
        "out_degree_matches": out_matches,
        "weight_multiset_matches": weight_matches,
        "self_edges": self_edges,
        "duplicate_edges": duplicates,
        "edges_shared_with_real_graph": shared,
        "fraction_shared_with_real_graph": shared / max(int(source.nnz), 1),
    }

    if preserved_groups:
        # Degree preservation keeps node identity, so declared sensory and
        # readout populations must be untouched by construction.
        record["groups"] = {
            name: {
                "size": len(indices),
                "in_degree_matches": bool(np.array_equal(source_in[indices], target_in[indices])),
                "out_degree_matches": bool(
                    np.array_equal(source_out[indices], target_out[indices])
                ),
            }
            for name, indices in preserved_groups.items()
        }

    failures: list[str] = []
    if not record["edge_count_matches"]:
        failures.append("edge count changed")
    if not in_matches:
        failures.append("in-degree sequence changed")
    if not out_matches:
        failures.append("out-degree sequence changed")
    if weight_matches is False:
        failures.append("weight multiset changed")
    if duplicates:
        failures.append(f"{duplicates} duplicate aggregated edges")
    record["failures"] = failures
    record["valid"] = not failures
    return record
